const warnedMissingKeys = new Set<string>();

export function getMessage(locale: Locale, key: string): string {
  const translated =
    playMessages[locale]?.[key] ??
    gameRoomMessages[locale]?.[key] ??
    (leaderboardMessages[locale] as Record<string, string> | undefined)?.[key] ??
    curatedMessages[locale]?.[key] ??
    familyMessages[locale]?.[key] ??
    aoiMessages[locale]?.[key] ??
    tsubakiMessages[locale]?.[key] ??
    journeyMessages[locale]?.[key] ??
    replayBranchMessages[locale]?.[key] ??
    practiceMessages[locale]?.[key] ??
    arcadeMessages[locale]?.[key] ??
    messages[locale]?.[key];
  if (translated !== undefined) return translated;
  if (process.env.NODE_ENV === 'development') {
    const id = `${locale}:${key}`;
    if (!warnedMissingKeys.has(id)) {
      warnedMissingKeys.add(id);
      console.warn(`[i18n] Missing ${id}`);
    }
  }
  return messages.zh[key] ?? key;
}

/** 替换文案中的 `{var}` 占位符（与 `t(key)` 不同，后者不支持变量）。 */
export function formatMessage(
  locale: Locale,
  key: string,
  vars: Record<string, string | number>,
): string {
  let template = getMessage(locale, key);
  for (const [k, v] of Object.entries(vars)) {
    template = template.split(`{${k}}`).join(String(v));
  }
  return template;
}

export const LOCALE_STORAGE_KEY = 'game-hub-locale';
const LOCALE_CHANGED_EVENT = 'game-hub:locale-changed';

export function subscribeStoredLocale(listener: () => void): () => void {
  window.addEventListener(LOCALE_CHANGED_EVENT, listener);
  window.addEventListener('storage', listener);
  return () => {
    window.removeEventListener(LOCALE_CHANGED_EVENT, listener);
    window.removeEventListener('storage', listener);
  };
}

export function getStoredLocale(): Locale {
  if (typeof gameStorage === 'undefined') return 'zh';
  const v = gameStorage.getItem(LOCALE_STORAGE_KEY);
  return v === 'en' ? 'en' : 'zh';
}

export function setStoredLocale(locale: Locale): void {
  gameStorage?.setItem(LOCALE_STORAGE_KEY, locale);
  if (typeof window !== 'undefined')
    window.dispatchEvent(new Event(LOCALE_CHANGED_EVENT));
}
